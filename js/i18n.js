// ---- Translation engine ----
function t(key) {
  const lang = getLang();
  return (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
}

function getLang() {
  return localStorage.getItem("tanit_lang") || "fr";
}

function setLang(lang) {
  localStorage.setItem("tanit_lang", lang);
  applyLang();
  document.querySelectorAll(".lang-switch button").forEach((b) => {
    b.classList.toggle("active", b.dataset.lang === lang);
  });
}

function applyLang() {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.body.classList.toggle("lang-ar", lang === "ar");
  document.body.classList.toggle("lang-fr", lang === "fr");
  document.body.classList.toggle("lang-en", lang === "en");
  if (lang === "ar") document.body.setAttribute("dir", "rtl");
  else document.body.setAttribute("dir", "ltr");

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  });

  const brand = document.querySelector(".brand-text");
  if (brand) brand.textContent = lang === "ar" ? window.SITE_NAME_AR : window.SITE_NAME;
  document.title = t("app.name");
}

// Format a date in the current language
function formatDate(iso) {
  if (!iso) return "";
  const d = new Date(iso);
  try {
    return d.toLocaleDateString(getLang() === "ar" ? "ar-TN" : getLang() === "en" ? "en-GB" : "fr-TN", {
      year: "numeric", month: "short", day: "numeric",
    });
  } catch (e) {
    return d.toLocaleDateString();
  }
}
